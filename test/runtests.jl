function _hpic_selected_groups()
    selected = get(ENV, "HPIC_TEST_GROUP", "all")
    selected == "all" && return eachindex(HPIC_TEST_GROUPS)
    group = tryparse(Int, selected)
    group !== nothing && 1 <= group <= length(HPIC_TEST_GROUPS) && return (group,)
    error(
        "HPIC_TEST_GROUP must be \"all\" or an integer in 1..$(length(HPIC_TEST_GROUPS)); got $(repr(selected))",
    )
end

@testset "HybridPlasmaPIC" begin
    for group in _hpic_selected_groups(), file in HPIC_TEST_GROUPS[group]
        t0 = time()
        include(file)
        println("[test timing] group=$group file=$file seconds=$(round(time() - t0; digits = 1))")
    end
end
